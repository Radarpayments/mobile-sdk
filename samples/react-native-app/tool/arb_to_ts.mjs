#!/usr/bin/env node
/*
 * Turns the Flutter sample's ARB files into src/l10n/messages.ts, so that both samples show the same texts in the
 * same nine languages. The Flutter ARB files come from the Android sample's string resources
 * (flutter-app/tool/android_strings_to_arb.py); run this after them:
 *
 *     node tool/arb_to_ts.mjs
 *
 * A text with `{name}` placeholders becomes a function of them in `Strings`, in the order the ARB metadata lists
 * them; an `int` placeholder takes a number.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const app = join(dirname(fileURLToPath(import.meta.url)), '..');
const arbDir = join(app, '..', 'flutter-app', 'lib', 'l10n');
const out = join(app, 'src', 'l10n', 'messages.ts');
const languages = ['en', 'ru', 'ro', 'el', 'bg', 'de', 'fr', 'es', 'ar'];

const read = language => JSON.parse(readFileSync(join(arbDir, `app_${language}.arb`), 'utf8'));
const english = read('en');
const keys = Object.keys(english).filter(key => !key.startsWith('@'));

const quote = text => `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n')}'`;

const placeholders = Object.fromEntries(
  keys.flatMap(key => {
    const names = Object.entries(english[`@${key}`]?.placeholders ?? {});
    return names.length
      ? [[key, names.map(([name, meta]) => ({ name, type: meta.type === 'int' ? 'number' : 'string' }))]]
      : [];
  }),
);

const signature = key =>
  placeholders[key]
    ? `  ${key}(${placeholders[key].map(({ name, type }) => `${name}: ${type}`).join(', ')}): string;`
    : `  ${key}: string;`;

const table = language => {
  const arb = read(language);
  const missing = keys.filter(key => typeof arb[key] !== 'string');
  if (missing.length) throw new Error(`app_${language}.arb lacks ${missing.join(', ')}`);
  return [`  ${language}: {`, ...keys.map(key => `    ${key}: ${quote(arb[key])},`), '  },'].join('\n');
};

writeFileSync(
  out,
  [
    '// Generated by tool/arb_to_ts.mjs from samples/flutter-app/lib/l10n/*.arb. Do not edit: change the texts there.',
    '',
    `export const languageCodes = [${languages.map(quote).join(', ')}] as const;`,
    '',
    'export type LanguageCode = (typeof languageCodes)[number];',
    '',
    '/** The texts of the demo; those with placeholders are functions of them. */',
    'export interface Strings {',
    ...keys.map(signature),
    '}',
    '',
    'export type MessageKey = keyof Strings;',
    '',
    '/** Names of the placeholders of each text that has any, in the order `Strings` takes them. */',
    'export const placeholders: Partial<Record<MessageKey, readonly string[]>> = {',
    ...Object.entries(placeholders).map(
      ([key, names]) => `  ${key}: [${names.map(({ name }) => quote(name)).join(', ')}],`,
    ),
    '};',
    '',
    'export const messages: Record<LanguageCode, Record<MessageKey, string>> = {',
    ...languages.map(table),
    '};',
    '',
  ].join('\n'),
);
console.log(`${out}: ${keys.length} texts in ${languages.length} languages`);
