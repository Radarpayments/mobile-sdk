package net.payrdr.mobile.payment.sdk.payment.ui.payer.phone

/**
 * Calling code, mobile number example and lengths of a country.
 *
 * @property iso ISO 3166-1 alpha-2 code
 * @property dialCode calling code without "+", e.g. `44`
 * @property example national mobile number used as the placeholder, e.g. `7400123456`
 * @property groups digit groups of a formatted national number, e.g. `[4, 6]` → `7400 123456`
 * @property lengths possible lengths of a national mobile number
 * @property nationalPrefix trunk prefix typed in national form, e.g. `0` in the UK; empty when none
 * @property isMain the country picked for a calling code shared by several countries (+1, +7, +44…)
 */
internal class PhoneCountry(
    val iso: String,
    val dialCode: String,
    val example: String,
    val groups: List<Int>,
    val lengths: List<Int>,
    val nationalPrefix: String,
    val isMain: Boolean,
)

/**
 * Countries of the gateway list with their phone metadata, generated from Google libphonenumber
 * `PhoneNumberMetadata.xml` (Apache License 2.0, https://github.com/google/libphonenumber).
 * Row: `ISO|dialCode|example|groups|lengths|nationalPrefix|main`.
 */
internal object PhoneCountries {
    val all: List<PhoneCountry> by lazy {
        TABLE.trimIndent().lines().map { row ->
            val c = row.split('|')
            PhoneCountry(
                iso = c[0],
                dialCode = c[1],
                example = c[2],
                groups = c[3].split(',').map(String::toInt),
                lengths = c[4].split(',').map(String::toInt),
                nationalPrefix = c[5],
                isMain = c[6] == "1",
            )
        }
    }

    private val byIso: Map<String, PhoneCountry> by lazy { all.associateBy { it.iso } }

    fun byIso(iso: String?): PhoneCountry? = iso?.uppercase()?.let { byIso[it] }

    /**
     * Country whose calling code starts [digits] (an international number without "+"), and the rest
     * of the digits. The longest code wins; for a shared code [preferred] wins if it has that code,
     * then the main country.
     */
    fun detect(
        digits: String,
        preferred: String? = null,
    ): Pair<PhoneCountry, String>? {
        for (length in MAX_DIAL_CODE_LENGTH downTo 1) {
            if (digits.length < length) continue
            val code = digits.take(length)
            val candidates = all.filter { it.dialCode == code }
            if (candidates.isEmpty()) continue
            val country =
                candidates.firstOrNull { it.iso == preferred?.uppercase() }
                    ?: candidates.firstOrNull { it.isMain }
                    ?: candidates.first()
            return country to digits.drop(length)
        }
        return null
    }

